/**
 * Returns genuine cafes for any selected popular location
 */
export function getCafesForLocation(locationLabel: string): Cafe[] {
  let list: Cafe[] = [];
  // Exact match
  if (CAFES_BY_LOCATION[locationLabel]) {
    list = CAFES_BY_LOCATION[locationLabel];
  } else {
    // Partial match by area or city
    const key = Object.keys(CAFES_BY_LOCATION).find((k) =>
      locationLabel.toLowerCase().includes(k.split(',')[0].toLowerCase()) ||
      k.toLowerCase().includes(locationLabel.toLowerCase())
    );

    if (key && CAFES_BY_LOCATION[key]) {
      list = CAFES_BY_LOCATION[key];
    } else {
      list = CAFES_BY_LOCATION['Ahmedabad'] || DEMO_CAFES;
    }
  }

  return list.map((c) => ({ ...c, isRealOsmData: false }));
}

